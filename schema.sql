-- ---------- Таблица заявок ----------
create table if not exists public.requests (
  id          bigint generated by default as identity primary key,
  owner_id    text        not null,              -- Telegram user_id (строка)
  title       text        not null,              -- что хочу купить
  amount      numeric     not null check (amount > 0),
  reason      text        not null,
  alternative text        not null default '',
  created_at  timestamptz not null default now()
);

create index if not exists requests_created_at_idx on public.requests (created_at desc);
create index if not exists requests_owner_idx     on public.requests (owner_id);

-- ---------- Таблица голосов ----------
create table if not exists public.votes (
  id         bigint generated by default as identity primary key,
  request_id bigint      not null references public.requests (id) on delete cascade,
  user_id    text        not null,
  side       text        not null check (side in ('for', 'against')),
  comment    text        not null default '',
  created_at timestamptz not null default now(),
  -- один голос на заявку от одного пользователя;
  -- код ловит нарушение этого ограничения по SQLSTATE 23505
  constraint votes_request_user_key unique (request_id, user_id)
);

create index if not exists votes_request_idx on public.votes (request_id);

-- ---------- Права доступа ----------
grant select, insert on public.requests to anon, authenticated;
grant select, insert on public.votes    to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ---------- Row Level Security ----------
alter table public.requests enable row level security;
alter table public.votes    enable row level security;

-- Лента общая: читают все.
drop policy if exists "requests_read_all"  on public.requests;
create policy "requests_read_all"  on public.requests
  for select to anon, authenticated using (true);

-- Создавать заявки может любой (анонимный суд).
drop policy if exists "requests_insert_all" on public.requests;
create policy "requests_insert_all" on public.requests
  for insert to anon, authenticated with check (true);

drop policy if exists "votes_read_all"  on public.votes;
create policy "votes_read_all"  on public.votes
  for select to anon, authenticated using (true);

drop policy if exists "votes_insert_all" on public.votes;
create policy "votes_insert_all" on public.votes
  for insert to anon, authenticated with check (true);

