create table if not exists public.requests (
  id          bigint generated by default as identity primary key,
  owner_id    text        not null,
  title       text        not null,
  amount      numeric(14,2) not null check (amount > 0),
  reason      text        not null,
  alternative text        not null default '',
  created_at  timestamptz not null default now()
);

create index if not exists requests_created_at_idx on public.requests (created_at desc);
create index if not exists requests_owner_idx     on public.requests (owner_id);

create table if not exists public.votes (
  id         bigint generated by default as identity primary key,
  request_id bigint      not null references public.requests (id) on delete cascade,
  user_id    text        not null,
  side       text        not null check (side in ('for', 'against')),
  comment    text        not null default '',
  created_at timestamptz not null default now(),
  constraint votes_request_user_key unique (request_id, user_id)
);

create index if not exists votes_request_idx on public.votes (request_id);

-- ---------- RLS ----------
alter table public.requests enable row level security;
alter table public.votes    enable row level security;

-- Доступ только для service_role / postgres (бэкенд).
-- anon и authenticated не получают ни select, ни insert:
-- браузер больше не ходит в Supabase напрямую.
revoke all on public.requests from anon, authenticated;
revoke all on public.votes    from anon, authenticated;

grant all on public.requests to service_role;
grant all on public.votes    to service_role;
grant usage, select on all sequences in schema public to service_role;

-- На всякий случай убираем старые публичные политики, если создавали раньше
drop policy if exists "requests_read_all"   on public.requests;
drop policy if exists "requests_insert_all" on public.requests;
drop policy if exists "votes_read_all"      on public.votes;
drop policy if exists "votes_insert_all"    on public.votes;
